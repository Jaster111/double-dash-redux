"""Write tools/recomp/functions.txt, the recompiler's list of known function starts, from the
analysis outputs (build/rea_procedures.json: REA/Ghidra procedures, build/matched_symbols.json:
link-map names, see tools/match_map.py).  The list is committed, so building needs neither.

  python tools/recomp/export_functions.py     (run from the project root)

Format: one function per line, "ADDRESS [NAME SIZE]" (hex address; name and byte size when the
function was matched to the link map).
"""
import json

OUT = "tools/recomp/functions.txt"


def main():
    funcs = {int(p["address"], 16): None for p in json.load(open("build/rea_procedures.json"))["normalized_result"]}
    for m in json.load(open("build/matched_symbols.json")):
        funcs[m["addr"]] = (m["name"], m.get("size") or 0)
    with open(OUT, "w", newline="\n") as f:
        f.write("# Function starts in main.dol (Mario Kart: Double Dash!! GM4P01) for tools/recomp/recomp.py.\n"
                "# Generated by tools/recomp/export_functions.py.  ADDRESS [NAME SIZE]\n")
        for a in sorted(funcs):
            f.write("%08X %s %d\n" % ((a,) + funcs[a]) if funcs[a] else "%08X\n" % a)
    print("%s: %d functions, %d named" % (OUT, len(funcs), sum(1 for v in funcs.values() if v)))


if __name__ == "__main__":
    main()
